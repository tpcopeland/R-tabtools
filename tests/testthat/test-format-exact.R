# The exact printf("%.df") / printf("%.de") formatter (src/stata_fmt.c)
# behind every displayed number. Expectations are glibc's printf output,
# which rounds the exact binary value with exact ties to even, as Stata's
# string(x, fmt) does. They are hard-coded, not compared with sprintf() at
# run time, because R's sprintf() on Windows rounds differently (0.45 ->
# "0.4", 97907712.5 -> "97907713"): the point is identical text everywhere.
# Inputs are hex literals so that no decimal parsing is involved.

test_that(".tt_fmt_f() and .tt_fmt_e() round the exact binary value, ties to even", {
  cases <- rbind(
    # x (hex), %.0f, %.1f, %.3f, %.3e
    c("0x1.ccccccccccccdp-2", "0", "0.5", "0.450", "4.500e-01"),         # 0.45
    c("-0x1.ccccccccccccdp-2", "-0", "-0.5", "-0.450", "-4.500e-01"),
    c("0x1.0624dd2f1a9fcp-11", "0", "0.0", "0.001", "5.000e-04"),        # 0.0005
    c("0x1.999999999999ap-5", "0", "0.1", "0.050", "5.000e-02"),         # 0.05
    c("-0x1.47ae147ae147bp-8", "-0", "-0.0", "-0.005", "-5.000e-03"),    # -0.005
    c("0x1.3333333333333p-3", "0", "0.1", "0.150", "1.500e-01"),         # 0.15
    c("0x1.5666666666666p+1", "3", "2.7", "2.675", "2.675e+00"),         # 2.675
    c("0x1p-1", "0", "0.5", "0.500", "5.000e-01"),                       # 0.5, a tie
    c("0x1.8p+0", "2", "1.5", "1.500", "1.500e+00"),
    c("0x1.4p+1", "2", "2.5", "2.500", "2.500e+00"),
    c("-0x1.4p+1", "-2", "-2.5", "-2.500", "-2.500e+00"),
    c("0x1.757d002p+26", "97907712", "97907712.5", "97907712.500", "9.791e+07"),
    c("0x1.2653e82p+26", "77156256", "77156256.5", "77156256.500", "7.716e+07"),
    c("0x1.0000000000001p-1", "1", "0.5", "0.500", "5.000e-01"),         # 0.5 + 1 ulp
    c("0x1.387cp+13", "10000", "9999.5", "9999.500", "1.000e+04"),       # 9999.5
    c("-0x1.47ae147ae147bp-5", "-0", "-0.0", "-0.040", "-4.000e-02"),
    c("-0x0p+0", "-0", "-0.0", "-0.000", "-0.000e+00"),
    c("0x0.0000000000001p-1022", "0", "0.0", "0.000", "4.941e-324"),     # smallest subnormal
    c("0x1.52d02c7e14af6p+76", "99999999999999991611392", "99999999999999991611392.0",
      "99999999999999991611392.000", "1.000e+23"),                     # 1e23
    c("0x1.b69b4ba630f35p+56", "123456789012345680", "123456789012345680.0",
      "123456789012345680.000", "1.235e+17"),
    c("0x1.3333333333334p-2", "0", "0.3", "0.300", "3.000e-01")          # 0.1 + 0.2
  )
  x <- as.numeric(cases[, 1])
  expect_identical(tabtools:::.tt_fmt_f(x, 0L), cases[, 2])
  expect_identical(tabtools:::.tt_fmt_f(x, 1L), cases[, 3])
  expect_identical(tabtools:::.tt_fmt_f(x, 3L), cases[, 4])
  expect_identical(tabtools:::.tt_fmt_e(x, 3L), cases[, 5])
})

test_that(".tt_fmt_e() handles the '#' flag, three-digit exponents and the largest double", {
  expect_identical(tabtools:::.tt_fmt_e(c(2e200, 9.6e-201, 5), 0L, alt = TRUE), c("2.e+200", "1.e-200", "5.e+00"))
  expect_identical(tabtools:::.tt_fmt_e(c(2e200, 5), 0L), c("2e+200", "5e+00"))
  expect_identical(tabtools:::.tt_fmt_e(.Machine$double.xmax, 5L), "1.79769e+308")
  expect_identical(tabtools:::.tt_fmt_e(9.9999996, 6L), "1.000000e+01")
  expect_identical(nchar(tabtools:::.tt_fmt_f(.Machine$double.xmax, 2L)), 312L)
  expect_identical(tabtools:::.tt_fmt_f(0.0625, 20L), "0.06250000000000000000")
})

test_that(".tt_fmt_f() recycles d, keeps length and prints non-finite values as sprintf() does", {
  expect_identical(tabtools:::.tt_fmt_f(c(1.25, 1.25, 1.25), 0:2), c("1", "1.2", "1.25"))
  expect_identical(tabtools:::.tt_fmt_f(numeric(), 2L), character())
  expect_identical(tabtools:::.tt_fmt_f(c(NA, NaN, Inf, -Inf), 2L), c("NA", "NaN", "Inf", "-Inf"))
})

test_that(".tt_fmt_sig() gives format(x, digits, scientific = FALSE) text", {
  expect_identical(tabtools:::.tt_fmt_sig(c(1234.5, 1234567.5, 1234568.5, 0.1 + 0.2, 100000, 1e-05, -2.5, 0),
                                          7L),
                   c("1234.5", "1234568", "1234568", "0.3", "100000", "0.00001", "-2.5", "0"))
  expect_identical(tabtools:::.tt_fmt_sig(c(1 / 3, 0.032, 123456789), 15L),
                   c("0.333333333333333", "0.032", "123456789"))
})

